class GuideDialog(QDialog):
    """Немодальное окно гайда с разделами и полной таблицей хоткеев."""

    def __init__(self, parent=None, theme='dark'):
        super().__init__(parent)
        self.setWindowTitle("Гайд")
        self.setWindowFlag(Qt.WindowContextHelpButtonHint, False)
        self.resize(980, 680)
        self._theme = 'light' if theme == 'light' else 'dark'
        self._current = 0

        root = QVBoxLayout(self)
        root.setContentsMargins(14, 12, 14, 10)
        root.setSpacing(8)

        title = QLabel("📖  Гайд по столу")
        title.setObjectName("guide_title")
        title.setStyleSheet(
            "font-family: 'DejaVu Serif', Georgia, serif;"
            "font-size: 20pt; font-weight: 700;")
        root.addWidget(title)
        subtitle = QLabel("Краткий мануал и все горячие клавиши. "
                          "Окно можно держать открытым во время игры.")
        subtitle.setWordWrap(True)
        subtitle.setStyleSheet("color: palette(mid);")
        root.addWidget(subtitle)

        body = QHBoxLayout()
        body.setSpacing(10)
        root.addLayout(body, 1)

        self.nav = QListWidget()
        self.nav.setObjectName("guide_nav")
        self.nav.setFixedWidth(230)
        for index, (name, _html) in enumerate(GUIDE_SECTIONS):
            item = QListWidgetItem(name)
            item.setData(Qt.UserRole, index)
            self.nav.addItem(item)
        self.nav.currentRowChanged.connect(self._show_section)
        body.addWidget(self.nav)

        self.view = QTextBrowser()
        self.view.setObjectName("guide_view")
        self.view.setOpenExternalLinks(False)
        self.view.setOpenLinks(False)
        body.addWidget(self.view, 1)

        footer = QHBoxLayout()
        hint = QLabel("Подсказка: правый клик по карте и токену открывает "
                      "все действия. Ctrl+Z отменяет почти всё.")
        hint.setWordWrap(True)
        hint.setStyleSheet("color: palette(mid);")
        footer.addWidget(hint, 1)
        close_btn = QPushButton("Закрыть")
        close_btn.clicked.connect(self.close)
        footer.addWidget(close_btn)
        root.addLayout(footer)

        self.set_theme(self._theme)
        self.nav.setCurrentRow(0)

    # ------------------------------------------------------------------
    def set_theme(self, theme):
        """Перекрасить текст и таблицы под тему стола."""
        self._theme = 'light' if theme == 'light' else 'dark'
        if self._theme == 'dark':
            self._colors = {
                'text': '#ddd9d1', 'accent': '#d6b877',
                'muted': '#9a968e', 'line': '#3a3a40',
            }
        else:
            self._colors = {
                'text': '#2c2a28', 'accent': '#85662a',
                'muted': '#6f6d66', 'line': '#d0cec7',
            }
        c = self._colors
        self.view.setStyleSheet(
            f"QTextBrowser {{ color: {c['text']}; padding: 10px 14px; }}")
        self.view.document().setDefaultStyleSheet(f"""
            body {{ color: {c['text']}; font-size: 10.5pt; }}
            h1 {{ color: {c['accent']}; font-size: 17pt; margin-bottom: 8px; }}
            h2 {{ color: {c['accent']}; font-size: 12pt; margin-top: 14px; }}
            p.muted {{ color: {c['muted']}; }}
            table {{ border-collapse: collapse; }}
            td {{ padding: 5px 8px; border-bottom: 1px solid {c['line']}; }}
            li {{ margin-bottom: 4px; }}
        """)
        self._show_section(self._current)

    def _show_section(self, index):
        if not GUIDE_SECTIONS:
            return
        index = max(0, min(int(index or 0), len(GUIDE_SECTIONS) - 1))
        self._current = index
        self.view.setHtml(GUIDE_SECTIONS[index][1])
        self.view.verticalScrollBar().setValue(0)

    def section_titles(self):
        return [name for name, _html in GUIDE_SECTIONS]

    def all_html(self):
        return "\n".join(html for _name, html in GUIDE_SECTIONS)
