def feature_name(monster, feature):
    """Русское имя особенности/атаки: ручная сверка либо данные dnd.su."""
    hand = NAME_RU.get(_key(monster, feature))
    if hand:
        return hand
    record = _data()["feature_texts"].get(_norm_key(monster), {}).get(
        _norm_key(feature))
    if record and record.get("name"):
        return record["name"]
    embedded = _data().get("embedded", {}).get(_norm_key(feature))
    if embedded and embedded.get("name"):
        return embedded["name"]
    # Общий словарь хранит термины строчными («когти»). В карточке это
    # название атаки, поэтому приводим к виду заголовка.
    title = _data()["titles"].get(_norm_key(feature))
    if title:
        return title[:1].upper() + title[1:]
    return None


def feature_text(monster, feature):
    """Полный русский правиловой текст особенности либо None."""
    hand = TEXT_RU.get(_key(monster, feature))
    if hand is not None:
        return hand
    record = _data()["feature_texts"].get(_norm_key(monster), {}).get(
        _norm_key(feature))
    if record:
        return record.get("text")
    # Встроенные заклинания/предметы монстра (Sacred Flame, Leather Armor)
    embedded = _data().get("embedded", {}).get(_norm_key(feature))
    if embedded and embedded.get("text"):
        return embedded["text"]
    # Общий текст особенности (мода по монстрам без собственной страницы)
    return _data().get("feature_global", {}).get(_norm_key(feature))
