import json
import os
import re

_DATA_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                          "dnd5e_loc_data.json")
_DATA = None


def _norm_key(text):
    """Ключ сопоставления: как в fetch_dnd5e_loc.norm_key (без скобок, ё->е)."""
    text = re.sub(r"\([^)]*\)", " ", str(text or "").casefold()).replace(
        "ё", "е")
    return re.sub(r"\s+", " ", re.sub(r"[^a-zа-яе0-9 ]+", " ",
                                       text)).strip()


def _data():
    global _DATA
    if _DATA is None:
        try:
            with open(_DATA_PATH, encoding="utf-8") as f:
                _DATA = json.load(f)
        except (OSError, ValueError):
            _DATA = {"monsters": {}, "titles": {}, "feature_texts": {}}
    return _DATA


def monster_name(en_name):
    """Русское имя монстра с dnd.su либо None."""
    record = _data()["monsters"].get(_norm_key(en_name))
    return record.get("name") if record else None


def title(en_name):
    """Русский термин из общего словаря dnd.su либо None.

    636 записей: названия атак, черт, заклинаний и предметов. Ключ
    нормализуется так же, как при сборке словаря.
    """
    if not en_name:
        return None
    return _data()["titles"].get(_norm_key(en_name))


def _key(monster, feature):
    return (str(monster or "").strip().casefold(),
            str(feature or "").strip().casefold())


