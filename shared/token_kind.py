"""Роль токена: персонаж игрока или актёр (НПС/существо).

На столе два разных документа, и раньше они были перепутаны в одном месте:

* **игрок** (``player``) — документ персонажа — лист Long Story Short.
  Характеристики, КД, атаки, инвентарь и состояния живут в листе, поэтому
  «карточка актёра» и «карточка существа» у такого токена ничего не
  добавляли: это была вторая, ни к чему не привязанная запись тех же чисел.
* **актёр** (``actor``) — документ существа — статблок: карточка существа
  для показа за столом и редактируемая карточка актёра для мастера.

Проверки ``kind == "player"`` были разбросаны по окну и холсту, и в
каждом новом месте легко было забыть про разделение — так у персонажа
игрока и открывалась карточка существа. Теперь правило одно и здесь:
этот модуль — единственная точка правды о том, что кому положено.
Остальные модули спрашивают предикаты, а не сравнивают строки.

Чистые функции без Qt и без сети: их можно проверить отдельно.
"""
#: Токен персонажа игрока — документ в листе LSS.
PLAYER = "player"
#: Токен актёра/НПС/существа — документ в статблоке.
ACTOR = "actor"

KINDS = (PLAYER, ACTOR)

KIND_LABELS = {
    PLAYER: "Игрок",
    ACTOR: "Актёр / НПС",
}


def kind_of(token) -> str:
    """Роль токена; неизвестное и пустое считаем актёром.

    Так безопаснее: у старых сохранений поле ``kind`` могло не быть вовсе,
    а актёр — это поведение по умолчанию для всех прежних токенов.
    """
    kind = getattr(token, "kind", ACTOR)
    return kind if kind in KINDS else ACTOR


def is_player(token) -> bool:
    """Токен персонажа игрока: его документ — лист LSS."""
    return kind_of(token) == PLAYER


def is_actor(token) -> bool:
    """Токен актёра/НПС: его документ — статблок."""
    return kind_of(token) == ACTOR


def has_actor_sheet(token) -> bool:
    """Есть ли у токена редактируемая карточка актёра (только у актёров)."""
    return is_actor(token)


def has_statblock(token) -> bool:
    """Есть ли у токена карточка существа (только у актёров)."""
    return is_actor(token)


def has_sheet_page(token) -> bool:
    """Появляется ли у токена страница во вкладке «Лист персонажа»."""
    return is_player(token)


def kind_label(token) -> str:
    """Подпись роли для интерфейса и подсказок."""
    return KIND_LABELS[kind_of(token)]
