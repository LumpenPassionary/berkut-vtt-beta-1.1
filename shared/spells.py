def _normalize_name(value) -> str:
    return " ".join(str(value or "").strip().casefold().replace("ё", "е")
                    .replace("-", " ").split())


def canonical(rec) -> str:
    """Ключ правила заклинания: ручной или слаг SRD.

    Сначала ручные правила: у них точные эффекты (Щит, Ускорение). Затем
    таблица SRD по английскому имени, русскому переводу или id LSS — так
    каждое из 319 заклинаний получает механику, а не только десять
    доведённых вручную.
    """
    if not isinstance(rec, dict):
        return ""
    source = str(rec.get("source_name") or "").strip()
    if source in _BY_SOURCE:
        return _BY_SOURCE[source]
    name = str(rec.get("name") or "").strip().casefold().replace("ё", "е")
    if name in _BY_EXACT:
        return _BY_EXACT[name]
    # Сначала точные имена SRD: иначе «Щит веры» попадает в правило «Щит»
    # по подстроке и получает неверный эффект.
    for value in (rec.get("source_name"), rec.get("name")):
        folded = str(value or "").strip().casefold().replace("ё", "е")
        if folded in _SRD_BY_EN:
            return _manual_key(_SRD_BY_EN[folded])
        if folded in _SRD_BY_RU:
            return _manual_key(_SRD_BY_RU[folded])
    lss_ref = str(rec.get("lss_ref") or rec.get("id") or "")
    if lss_ref in _SRD_BY_LSS:
        return _manual_key(_SRD_BY_LSS[lss_ref])
    # «Acid Arrow» / «acid-arrow» / «Кислотная стрела» — одно и то же.
    for value in (rec.get("source_name"), rec.get("name")):
        folded = _normalize_name(value)
        if not folded:
            continue
        for slug, rule in _SRD.items():
            if _normalize_name(rule.get("n")) == folded:
                return _manual_key(slug)
            if _normalize_name(rule.get("ru")) == folded:
                return _manual_key(slug)
    # Только теперь — неточное совпадение (старые листы без source_name).
    text = _text(rec)
    for first, second, key in _BY_NAME:
        if first in text and (not second or second in text):
            return key
    return ""


