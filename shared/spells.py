def _duration_label(rec: dict, rule: dict, rounds: int) -> str:
    """Длительность по-русски: «концентрация, до 1 минуты»."""
    raw = str(rec.get("duration") or "").strip()
    if not raw:
        raw = str(rule.get("dur") or "").strip()
    low = raw.casefold()
    if not raw or low in ("instantaneous", "мгновенно"):
        return f"{rounds} раунд(ов)" if rounds else ""
    text = re.sub(r"^concentration,?\s*", "", low)
    up_to = bool(re.search(r"\bup to\b", text))
    text = re.sub(r"\bup to\b", "", text)

    def _unit(match):
        value = int(match.group(1))
        unit = match.group(2)
        if unit.startswith("round"):
            word = ("раунд" if value % 10 == 1 and value % 100 != 11
                    else "раундов")
        elif unit.startswith("minute"):
            word = ("минута" if value % 10 == 1 and value % 100 != 11
                    else "минут")
        elif unit.startswith("hour"):
            if value % 10 == 1 and value % 100 != 11:
                word = "час"
            elif value % 10 in (2, 3, 4) and value % 100 not in (12, 13, 14):
                word = "часа"
            else:
                word = "часов"
        elif unit.startswith("day"):
            word = "день" if value % 10 == 1 else "дней"
        else:
            word = unit
        return f"{value} {word}"

    text = re.sub(r"(\d+)\s*(rounds?|minutes?|hours?|days?)", _unit, text)
    text = text.strip(" ,")
    if up_to:
        text = "до " + text
    if low.startswith("concentration"):
        text = "концентрация, " + text
    return text.strip(", ")


