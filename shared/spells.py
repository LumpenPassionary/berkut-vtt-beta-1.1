def character_total_level(sheet: dict) -> int:
    """Уровень персонажа для заговоров: сумма уровней всех классов.

    Заговоры растут по уровню ПЕРСОНАЖА, а не по уровню класса, и у
    мультикласса это сумма: «Следопыт 5 / Плут 3 / Воин 3» — 11 уровень,
    поэтому кости заговора утраиваются. Уровни классов берём там же, где
    их берут классовые особенности: из шапки листа и заметок.
    """
    sheet = sheet if isinstance(sheet, dict) else {}
    total = 0
    try:
        from shared import class_features
        levels = class_features.class_levels(sheet)
    except Exception:       # лист без классов вовсе — считаем по уровню
        levels = {}
    if isinstance(levels, dict):
        for value in levels.values():
            try:
                total += max(0, int(value or 0))
            except (TypeError, ValueError):
                continue
    try:
        stored = lss.character_level(sheet)
    except Exception:
        stored = 0
    return max(0, min(20, max(total, stored or 0)))


def cantrip_step(sheet: dict) -> int:
    """Сколько наборов костей добавляет уровень: 5/11/17 → +1/+2/+3."""
    level = character_total_level(sheet)
    if level >= 17:
        return 3
    if level >= 11:
        return 2
    if level >= 5:
        return 1
    return 0


def cantrip_dice(dice: str, sheet: dict) -> str:
    """Кости заговора по уровню персонажа: 1к8 → 2к8 (5), 3к8 (11), 4к8 (17)."""
    text = str(dice or "").strip()
    steps = cantrip_step(sheet)
    if steps <= 0:
        return text
    match = re.fullmatch(r"(\d*)d(\d+)(.*)", text)
    if not match:
        return text
    count = int(match.group(1) or 1) * (steps + 1)
    return f"{count}d{match.group(2)}{match.group(3)}"


