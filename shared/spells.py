#: Кубик урона на попадании: у большинства этих заклинаний d6, у
#: Ослепляющей кары — d8, у Изгоняющей — d10. Размер хранится в таблице
#: (`die`), у последствий — отдельно (`rider_die`, у Града шипов d10).
_SMITE_STEP_CAP = 8


def smite_dice(key: str, slot_level: int = 0) -> str:
    """Кубики урона на попадании по кругу ячейки: 2к6, 3к6, 4к6…

    Единая точка правды для клиента и сервера: и подпись в карточке, и
    урон на попадании считаются одной формулой, поэтому обещанное число
    всегда совпадает с броском. У Опутывающего удара урона на попадании
    нет — пустая строка.
    """
    rule = SMITE_SPELLS.get(str(key or "").strip().casefold())
    if not rule:
        return ""
    base = int(rule.get("dice") or 0)
    up = int(rule.get("up") or 0)
    if base <= 0 and up <= 0:
        return ""
    # Круг заклинания — часть правила: Клеймящая кара даёт 2к6 уже вторым
    # кругом, а 3к6 только третьим. Без этого она получала бы лишнюю кость.
    base_level = max(1, int(rule.get("level") or 1))
    steps = max(0, min(_SMITE_STEP_CAP,
                       int(slot_level or base_level) - base_level))
    count = base + steps * up
    die = str(rule.get("die") or "d6")
    return f"{count}{die}" if count > 0 else ""


def smite_rider_dice(key: str, slot_level: int = 0) -> str:
    """Кубики урона последствия: кольцо шипов и лоза (1к6/1к10 и выше)."""
    rule = SMITE_SPELLS.get(str(key or "").strip().casefold())
    if not rule:
        return ""
    base = int(rule.get("rider_dice") or 0)
    if base <= 0:
        return ""
    base_level = max(1, int(rule.get("level") or 1))
    steps = max(0, min(_SMITE_STEP_CAP,
                       int(slot_level or base_level) - base_level))
    count = base + steps * int(rule.get("rider_up") or 0)
    die = str(rule.get("rider_die") or "d6")
    return f"{count}{die}" if count > 0 else ""


#: Заговоры, которые растут числом ЛУЧЕЙ, а не костями: в 5e каждый луч
#: Мистического заряда — отдельный бросок атаки. Стол пока бросает одну
#: атаку, поэтому кости здесь не удваиваем (иначе на 17 уровне вышло бы
#: 4к10 одним броском), а правило честно пишем в подписи заклинания.
