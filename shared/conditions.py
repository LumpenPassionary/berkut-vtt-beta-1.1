def normalize_immunities(values) -> list:
    """Иммунитеты статблока -> канонические названия состояний."""
    out = []
    for value in values or []:
        key = _key(value)
        name = _IMMUNITY_ALIASES.get(key) or canonical(value)
        if name and name not in out:
            out.append(name)
    return out


def is_immune(condition, immunities) -> bool:
    """Иммунно ли существо к этому состоянию (с учётом форм записи)."""
    canon = canonical(condition)
    if not canon:
        return False
    return canon in normalize_immunities(immunities)


def exhaustion_level(conditions) -> int:
    """Уровень истощения: «Истощён 3» -> 3, без цифры -> 1.

    Уровень — не отдельное поле, а приписка в названии: состояние хранится
    списком строк, и менять формат ради одного числа было бы дороже.
    """
    level = 0
    for name in conditions or []:
        text = str(name or "").strip()
        if _key(text) != "истощен" and not _key(text).startswith("истощен"):
            continue
        digits = "".join(ch if ch.isdigit() else " " for ch in text).split()
        try:
            value = int(digits[0]) if digits else 1
        except ValueError:
            value = 1
        level = max(level, max(1, min(6, value)))
    return level


def normalize(conditions) -> list:
    """Список канонических имён без дублей. Неизвестное отбрасывается."""
    out = []
    for name in conditions or []:
        canon = canonical(name)
        if canon and canon not in out:
            out.append(canon)
    return out


def clean(conditions) -> list:
    """Имена для хранения: канон из справочника, у истощения — уровень.

    «истощён 3» сохраняется как «Истощён 3»: уровень — часть названия, иначе
    правила не смогут отличить первую степень от пятой.
    """
    out = []
    for value in conditions or []:
        canon = canonical(value)
        if not canon:
            continue
        name = canon
        if canon == "Истощён":
            level = exhaustion_level([value])
            name = canon if level <= 1 else f"{canon} {level}"
        if name not in out:
            out.append(name)
    return out


def flags(conditions) -> dict:
    """Свести состояния к флагам, которые понимает расчёт боя."""
    keys = {_key(n) for n in conditions or [] if n}
    exhaustion = exhaustion_level(conditions)

    def has(*names):
        return any(_key(n) in keys for n in names)

    incapacitated = has(*_NO_ACTIONS)
    speed_zero = has(*_IMMOBILE) or exhaustion >= 5
    hard_save_fail = has("парализован", "окаменел", "ошеломлён", "без сознания")
    # Преимущество атакующим по цели, не считая «сбит с ног»: у лежачего
    # оно только в упоре, поэтому его правило считается отдельно.
    advantage_other = has("ослеплён", "опутан", "парализован", "окаменел",
                          "ошеломлён", "без сознания")
    return {
        "names": sorted(keys),
        # «Не может действовать» — атаки, заклинания, предметы.
        "incapacitated": incapacitated,
        "no_actions": incapacitated,
        "no_reactions": incapacitated,
        # Скорость 0: схвачен, опутан, парализован, окаменел, ошеломлён,
        # без сознания, истощение 5+.
        "speed_zero": speed_zero,
        # По этому токену бьют с преимуществом (сбит с ног — только в упор,
        # это уточняет attack_modifiers).
        "attack_advantage": advantage_other or has("сбит с ног"),
        # То же преимущество без «сбит с ног»: у лежачего оно зависит от
        # дистанции, поэтому при подсчёте броска эти два правила разделены.
        "attack_advantage_other": advantage_other,
        # Сам токен бьёт с помехой.
        "attack_disadvantage": has("ослеплён", "испуган", "отравлен",
                                   "опутан", "сбит с ног") or exhaustion >= 3,
        # Попадание в упор — критическое.
        "auto_crit": has(*_AUTO_CRIT),
        "str_save_fail": hard_save_fail,
        "dex_save_fail": hard_save_fail,
        # Помеха на спасброски: опутанный — на Ловкость, истощение 3+ — на все.
        "save_disadvantage": has("опутан") or exhaustion >= 3,
        # Проверки характеристик: отравлен, испуган, ослеплён, истощение 1+.
        "check_disadvantage": (has("отравлен", "испуган", "ослеплён")
                               or exhaustion >= 1),
        # Окаменение даёт сопротивление всему урону.
        "damage_resist_all": has("окаменел"),
        "invisible": has("невидим"),
        # Скрытность — положение, а не состояние SRD: существа не видно,
        # пока оно себя не выдаст атакой. Для бросков это то же «не видит»,
        # поэтому преимущество/помеха считается как у невидимого.
        "hidden": has("скрыт"),
        "prone": has("сбит с ног"),
        "charmed": has("очарован"),
        "frightened": has("испуган"),
        "exhaustion": exhaustion,
    }


def attack_modifiers(attacker_conditions, target_conditions,
                     within_5ft: bool = True) -> dict:
    """Преимущество, помеха и автокрит для атаки с учётом состояний.

    ``within_5ft`` — расстояние между токенами на карте. От него зависят
    два правила: сбитый с ног даёт преимущество только в упоре, а паралич
    и без сознания делают попадание в упоре критическим.
    """
    attacker = flags(attacker_conditions)
    target = flags(target_conditions)
    advantage = False
    disadvantage = False
    notes = []

    # --- атакующий ---
    if attacker["invisible"] or attacker["hidden"]:
        advantage = True
        notes.append("атакующий невидим или скрыт (+преимущество)")
    if attacker["attack_disadvantage"]:
        disadvantage = True
        if attacker["frightened"]:
            notes.append("испуган (-помеха)")
        elif attacker["prone"]:
            notes.append("сбит с ног (-помеха)")
        elif attacker["exhaustion"] >= 3:
            notes.append("истощение (-помеха)")
        else:
            notes.append("состояние атакующего (-помеха)")

    # --- цель ---
    # Преимущество и помеха считаются раздельно, а не через elif: в 5e они
    # складываются и только потом гасят друг друга. Иначе лежачий на
    # расстоянии (помеха) вместе с ослеплением (преимущество) давал бы
    # чистую помеху вместо обычного броска.
    target_advantage = False
    target_disadvantage = False
    if target["invisible"] or target["hidden"]:
        target_disadvantage = True
        notes.append("цель невидима или скрыта (-помеха)")
    if target["attack_advantage_other"]:
        target_advantage = True
        notes.append("цель беспомощна (+преимущество)")
    if target["prone"]:
        if within_5ft:
            target_advantage = True
            notes.append("цель сбита с ног в упоре (+преимущество)")
        else:
            # По лежачему издалека бить неудобнее: преимущество пропадает,
            # появляется помеха.
            target_disadvantage = True
            notes.append("цель сбита с ног, атака не в упор (-помеха)")
    advantage = advantage or target_advantage
    disadvantage = disadvantage or target_disadvantage

    auto_crit = bool(target["auto_crit"] and within_5ft)
    if auto_crit:
        notes.append("попадание в упор — критическое")
    return {
        "advantage": bool(advantage),
        "disadvantage": bool(disadvantage),
        "auto_crit": auto_crit,
        "notes": notes,
        "target_flags": target,
        "attacker_flags": attacker,
    }


def save_modifiers(conditions, ability: str) -> dict:
    """Автопровал и помеха для спасброска конкретной характеристики.

    * паралич, ошеломление, окаменение и без сознания — автопровал
      спасбросков Силы и Ловкости;
    * опутанный бросает спасброски Ловкости с помехой;
    * истощение 3+ даёт помеху на все спасброски.
    """
    ability = str(ability or "").strip().casefold()
    info = flags(conditions)
    auto_fail = ((ability == "str" and info["str_save_fail"])
                 or (ability == "dex" and info["dex_save_fail"]))
    disadvantage = False
    if info["exhaustion"] >= 3:
        disadvantage = True
    elif ability == "dex" and "опутан" in info["names"]:
        disadvantage = True
    notes = []
    if auto_fail:
        notes.append("автопровал: состояние не даёт двигаться")
    if disadvantage:
        notes.append("помеха на спасбросок")
    return {"auto_fail": auto_fail, "disadvantage": disadvantage,
            "notes": notes, "flags": info}


def damage_factor(conditions) -> float:
    """Множитель входящего урона: окаменение — сопротивление всему (0.5)."""
    return 0.5 if flags(conditions)["damage_resist_all"] else 1.0


def can_act(conditions, dead: bool = False, hp=None) -> tuple:
    """Может ли токен действовать: (да/нет, причина для чата).

    Ноль хитов — тоже «не может»: по правилам 5e существо без хитов
    падает без сознания и кидает спасброски от смерти, а не атакует.
    """
    if dead:
        return False, "мёртв"
    if hp is not None and int(hp) <= 0:
        return False, "без сознания (0 хитов)"
    info = flags(conditions)
    if info["exhaustion"] >= 6:
        return False, "истощение 6 — смерть"
    if not info["incapacitated"]:
        return True, ""
    labels = {
        "недееспособен": "недееспособен",
        "парализован": "парализован",
        "окаменел": "окаменел",
        # Ключи здесь без «ё»: имена состояний сравниваются в _key.
        "ошеломлен": "ошеломлён",
        "без сознания": "без сознания",
    }
    for key in info["names"]:
        if key in labels:
            return False, labels[key]
    return False, "недееспособен"


def can_move(conditions, dead: bool = False, hp=None) -> tuple:
    """Может ли токен двигаться сам: (да/нет, причина для чата)."""
    if dead:
        return False, "мёртв"
    if hp is not None and int(hp) <= 0:
        return False, "без сознания (0 хитов)"
    info = flags(conditions)
    if info["exhaustion"] >= 6:
        return False, "истощение 6 — смерть"
    if not info["speed_zero"]:
        return True, ""
    labels = {
        "схвачен": "схвачен — скорость 0",
        "опутан": "опутан — скорость 0",
        "парализован": "парализован",
        "окаменел": "окаменел",
        "ошеломлен": "ошеломлён",
        "без сознания": "без сознания",
    }
    for key in info["names"]:
        if key in labels:
            return False, labels[key]
    if info["exhaustion"] >= 5:
        return False, "истощение 5 — скорость 0"
    return False, "скорость 0"


def rules_text(name) -> str:
    """Текст правил состояния для подсказки: по строке на эффект."""
    canon = canonical(name)
    if not canon:
        return ""
    lines = CONDITION_RULES.get(canon) or []
    return "\n".join(f"• {line}" for line in lines)


def describe(conditions) -> str:
    """Короткая сводка активных состояний для строки статуса."""
    parts = []
    seen = set()
    for value in conditions or []:
        canon = canonical(value)
        if not canon:
            continue
        name = canon
        if canon == "Истощён":
            # Уровень — часть названия, поэтому показываем его как есть.
            level = exhaustion_level([value])
            name = canon if level <= 1 else f"{canon} {level}"
        if name.casefold() in seen:
            continue
        seen.add(name.casefold())
        summary = CONDITION_SUMMARY.get(canon)
        parts.append(f"{name} ({summary})" if summary else name)
    return "; ".join(parts)
