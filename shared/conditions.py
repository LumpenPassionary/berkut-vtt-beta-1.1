def _key(name) -> str:
    return str(name or "").strip().casefold().replace("ё", "е")


def _canonical_map() -> dict:
    """Ключ без «ё» и регистра -> каноническое название из справочника."""
    return {_key(name): name for name in sheet_items.CONDITIONS_RU}


def canonical(name):
    """Каноническое название состояния или None, если такого нет.

    «Истощён 3» — тоже известное состояние: уровень истощения читается
    из названия, хвост из цифр не мешает узнать само состояние.
    """
    key = _key(name)
    if not key:
        return None
    known = _canonical_map()
    if key in known:
        return known[key]
    for canon_key, canon_name in known.items():
        if key.startswith(canon_key + " ") or key.startswith(canon_key + "("):
            return canon_name
    return None


